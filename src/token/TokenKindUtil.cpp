    bool TokenKindUtil::isGeneralizedIdentifier(TokenKind kind) {
        if (kind == TokenKind::IDENTIFIER) {
            return true;
        }

        bool isKeyword = false;

        for (auto& [keyword, keywordKind] : Lexer::getKeywords()) {
            if (kind == keywordKind) {
                isKeyword = true;
                break;
            }
        }

        return isKeyword;
    }
